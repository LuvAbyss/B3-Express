"""Rebuild the embedded BC3 encoder SPIR-V (src/nx/gpu/vk/bc3_spv.h) from shaders/bc3.comp, with the glslang of
build-fsr1-shader.py. The checked-in header is the compiled shader, so builds need no shader compiler."""

from pathlib import Path
import struct
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
source = root / 'src/nx/gpu/vk/shaders/bc3.comp'
glslang = next((root / '.cache/tools/glslang-16.6.0/bin').glob('glslang*.exe'))
with tempfile.TemporaryDirectory() as d:
    out = Path(d) / 'bc3.spv'
    subprocess.run([str(glslang), '-V', '--target-env', 'vulkan1.3', '-o', str(out), str(source)], check=True)
    data = out.read_bytes()
code = struct.unpack(f'<{len(data) // 4}I', data)
rows = [', '.join(f'0x{w:08x}u' for w in code[i : i + 9]) for i in range(0, len(code), 9)]
(root / 'src/nx/gpu/vk/bc3_spv.h').write_text(
    '/* SPDX-License-Identifier: GPL-3.0-or-later\n   Copyright 2026 the ScarletNX contributors */\n'
    '/* Generated by scripts/build-bc3-shader.py from shaders/bc3.comp. */\n'
    '#include <stdint.h>\n'
    'static const uint32_t bc3_spv[] = {\n    ' + ',\n    '.join(rows) + '};\n',
    newline='\n',
)
print(len(code), 'words')
